"""
Heart Disease Prediction - Streamlit App
=========================================
Interactive web app that loads the trained model and predicts the
likelihood of heart disease from patient inputs.

Run locally with:
    streamlit run app/app.py
"""

import joblib
import numpy as np
import pandas as pd
import streamlit as st

st.set_page_config(page_title="Heart Disease Predictor", page_icon="❤️", layout="centered")

MODEL_PATH = "model/heart_disease_model.pkl"
SCALER_PATH = "model/scaler.pkl"
FEATURES_PATH = "model/feature_names.pkl"


@st.cache_resource
def load_artifacts():
    model = joblib.load(MODEL_PATH)
    scaler = joblib.load(SCALER_PATH)
    feature_names = joblib.load(FEATURES_PATH)
    return model, scaler, feature_names


model, scaler, feature_names = load_artifacts()

st.title("❤️ Heart Disease Prediction")
st.write(
    "Enter the patient's clinical details below. This tool uses a machine "
    "learning model (trained on the UCI Cleveland Heart Disease dataset) to "
    "estimate the likelihood of heart disease. **This is an educational demo, "
    "not a medical diagnostic tool.**"
)

with st.form("patient_form"):
    col1, col2 = st.columns(2)

    with col1:
        age = st.number_input("Age", min_value=1, max_value=120, value=54)
        sex = st.selectbox("Sex", options=[("Male", 1), ("Female", 0)], format_func=lambda x: x[0])
        cp = st.selectbox(
            "Chest Pain Type",
            options=[
                ("Typical Angina", 0), ("Atypical Angina", 1),
                ("Non-anginal Pain", 2), ("Asymptomatic", 3),
            ],
            format_func=lambda x: x[0],
        )
        trestbps = st.number_input("Resting Blood Pressure (mm Hg)", min_value=80, max_value=220, value=130)
        chol = st.number_input("Serum Cholesterol (mg/dl)", min_value=100, max_value=600, value=246)
        fbs = st.selectbox("Fasting Blood Sugar > 120 mg/dl", options=[("No", 0), ("Yes", 1)], format_func=lambda x: x[0])
        restecg = st.selectbox(
            "Resting ECG Result",
            options=[("Normal", 0), ("ST-T Abnormality", 1), ("LV Hypertrophy", 2)],
            format_func=lambda x: x[0],
        )

    with col2:
        thalach = st.number_input("Max Heart Rate Achieved", min_value=60, max_value=220, value=150)
        exang = st.selectbox("Exercise Induced Angina", options=[("No", 0), ("Yes", 1)], format_func=lambda x: x[0])
        oldpeak = st.number_input("ST Depression (oldpeak)", min_value=0.0, max_value=10.0, value=1.0, step=0.1)
        slope = st.selectbox(
            "Slope of Peak Exercise ST Segment",
            options=[("Upsloping", 0), ("Flat", 1), ("Downsloping", 2)],
            format_func=lambda x: x[0],
        )
        ca = st.selectbox("Number of Major Vessels (0-4)", options=[0, 1, 2, 3, 4])
        thal = st.selectbox(
            "Thalassemia",
            options=[("Normal", 1), ("Fixed Defect", 2), ("Reversible Defect", 3)],
            format_func=lambda x: x[0],
        )

    submitted = st.form_submit_button("Predict")

if submitted:
    row = {
        "age": age, "sex": sex[1], "cp": cp[1], "trestbps": trestbps,
        "chol": chol, "fbs": fbs[1], "restecg": restecg[1], "thalach": thalach,
        "exang": exang[1], "oldpeak": oldpeak, "slope": slope[1], "ca": ca,
        "thal": thal[1],
    }
    input_df = pd.DataFrame([row])[feature_names]
    scaled_input = scaler.transform(input_df)

    prediction = model.predict(scaled_input)[0]
    probability = model.predict_proba(scaled_input)[0][1]

    st.subheader("Result")
    if prediction == 1:
        st.error(f"⚠️ High likelihood of heart disease — estimated probability: {probability:.1%}")
    else:
        st.success(f"✅ Low likelihood of heart disease — estimated probability: {probability:.1%}")

    st.progress(min(int(probability * 100), 100))
    st.caption(
        "This prediction is generated by a statistical model for educational purposes only "
        "and should never replace professional medical advice."
    )

st.divider()
st.caption("Heart Disease Prediction — AI/ML Internship Project")
